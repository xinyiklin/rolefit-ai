import assert from "node:assert/strict";
import { answerQualityFixtures } from "./fixtures/application-answer-quality.mjs";
import { answerHoldoutFixtures } from "./fixtures/application-answer-holdout.mjs";
import { answerExpandedFixtures } from "./fixtures/application-answer-expanded.mjs";
import { ANSWER_BENCHMARK_ARMS, ANSWER_BENCHMARK_JUDGES, answerControlChecks, blindAnswers, fixtureRequest, hash, judgePrompts, parseAnswerJudgment, summarizeAnswers, compareAnswerSettings } from "./support/application-answer-quality.mjs";
import { ANSWER_JUDGE_PROTOCOL, ANSWER_JUDGE_RUBRIC } from "./support/application-answer-judge-protocol.mjs";
import { evaluateAnswer, evaluateAnswerJudge, benchmarkSelection, carryFailedAttempt } from "./application-answer-quality-eval.mjs";
import { extractAnswerConstraints, validateAnswerConstraints } from "../../../shared/applicationAnswersContract.ts";
import { parseApplicationAnswerRequest } from "../applicationAnswerConversation.ts";

assert.equal(answerQualityFixtures.length, 12);
assert.equal(answerHoldoutFixtures.length, 7);
assert.equal(new Set(answerHoldoutFixtures.map(({ resumeText }) => resumeText)).size, 4);
assert.ok(answerHoldoutFixtures.every(({ id }) => !answerQualityFixtures.some((fixture) => fixture.id === id)));
assert.deepEqual(ANSWER_BENCHMARK_ARMS.map(({ id }) => id), ["opus-low", "opus-medium", "opus-high", "sol-low", "sol-medium", "sol-high", "sonnet-low", "sonnet-medium", "sonnet-high"]);
assert.deepEqual(ANSWER_BENCHMARK_JUDGES.map(({ id }) => id), ["astra-high", "opus-high"]);
assert.equal(hash(ANSWER_JUDGE_RUBRIC), ANSWER_JUDGE_PROTOCOL.rubricHash, "grading uses the exact rubric both judges approved");
assert.ok(ANSWER_JUDGE_PROTOCOL.approvedBy.every((judge) => judge.approved && judge.reasoningEffort === "high"));
const expanded = benchmarkSelection(["--dry-run", "--expanded"]);
assert.equal(answerExpandedFixtures.length, 38);
assert.equal(expanded.fixtures.length, 57);
assert.equal(new Set(expanded.fixtures.map(({ id }) => id)).size, 57);
assert.equal(new Set(answerExpandedFixtures.map(({ contextId }) => contextId)).size, 13);
assert.equal(expanded.fixtures.filter(({ cohort }) => cohort === "regression").length, 19);
assert.equal(expanded.fixtures.length * ANSWER_BENCHMARK_ARMS.length, 513);
assert.equal(expanded.fixtures.length * ANSWER_BENCHMARK_JUDGES.length, 114);
assert.equal(benchmarkSelection(["--run", "--expanded", "--resume=2026-10-07-abc"]).resume, "2026-10-07-abc");
for (const args of [["--run", "--holdout", "--expanded"], ["--run", "--resume=../private"], ["--dry-run", "--resume=x"], ["--run", "--expanded", "--expanded"], ["--run", "--unknown"]]) assert.throws(() => benchmarkSelection(args));
for (const fixture of expanded.fixtures) {
  parseApplicationAnswerRequest(fixtureRequest(fixture, ANSWER_BENCHMARK_ARMS[0]));
  assert.ok(fixture.expectation && fixture.family);
  if (fixture.expectedAnswer) assert.ok(validateAnswerConstraints(fixture.expectedAnswer, extractAnswerConstraints(fixture.question)).compliant, fixture.id);
  if (fixture.protectedText) assert.ok(fixture.previousAnswer.text.includes(fixture.protectedText), fixture.id);
}
assert.ok(answerQualityFixtures.find((item) => item.id === "long-question").question.length > 400);
assert.equal(new Set(answerQualityFixtures.map(({ id }) => id)).size, 12);
const fixture = answerQualityFixtures[0];
const arm = ANSWER_BENCHMARK_ARMS[0];
const result = await evaluateAnswer(fixture, arm, async (body, { stats }) => {
  assert.deepEqual(body, fixtureRequest(fixture, arm));
  stats.attempts = 2;
  stats.usage = { totalTokens: 123, costUsd: null };
  return { answer: "A specific draft", status: "ready", compliant: true, counts: validateAnswerConstraints("A specific draft", []).counts };
});
assert.equal(result.attempts, 2);
assert.equal(result.usage.totalTokens, 123);
assert.ok(result.checks.every(({passed})=>passed));
const exactFixture = answerExpandedFixtures.find(({expectedAnswer})=>expectedAnswer);
const exact = text => ({answer:text,status:"ready",counts:validateAnswerConstraints(text,[]).counts});
assert.ok(answerControlChecks(exactFixture,exact(exactFixture.expectedAnswer)).every(({passed})=>passed));
assert.equal(answerControlChecks(exactFixture,exact(exactFixture.expectedAnswer+' Extra.')).find(({check})=>check==="exact-requested-answer").passed,false,"narrow over-edits fail independently of judge opinion");
const protectedFixture = answerExpandedFixtures.find(({protectedText})=>protectedText);
const protectedFailure = answerControlChecks(protectedFixture,exact("An entirely rewritten answer."));
assert.equal(protectedFailure.find(({check})=>check==="protected-text-unchanged").passed,false);
assert.equal(summarizeAnswers([{arm:ANSWER_BENCHMARK_ARMS[0].id,fixture:protectedFixture.id,answer:exact("An entirely rewritten answer."),checks:protectedFailure}],[])[0].deterministicChecks.failures.length,1,"live summaries retain deterministic control failures");
const failed = await evaluateAnswer(fixture, arm, async () => { throw new Error("PRIVATE provider body"); });
assert.equal(failed.error, "provider-or-response");
assert.ok(!JSON.stringify(failed).includes("PRIVATE"));
const blind = blindAnswers(fixture.id, [result], "judge");
assert.equal(judgePrompts(fixture, blind).userPrompt.includes('"arm"'), false);
assert.deepEqual(JSON.parse(judgePrompts(fixture,blind).userPrompt).answers[0].mechanicalChecks,result.checks);
const counted = blindAnswers(fixture.id, [{ ...result, answer: { ...result.answer, counts: { words: 99, characters: 612, sentences: 4 } } }], "judge");
const judgeInput = JSON.parse(judgePrompts(fixture, counted).userPrompt);
assert.deepEqual(judgeInput.answers[0].counts, { words: 99, characters: 612, sentences: 4 }, "judges receive exact app counts instead of estimating limits");
assert.equal(judgeInput.detectedConstraints[0].max, 100);
const rating = { label: "A", naturalness: 4, evidence: 5, readability: 4, instructions: 5, economy: 4, usable: true, severeFabrication: false, evidenceConcern: "none", missingParts: [], reason: "Specific and supported." };
assert.equal(parseAnswerJudgment({ ratings: [rating] }, blind)[0].score, 88);
assert.throws(() => parseAnswerJudgment({ ratings: [{ ...rating, evidence: 6 }] }, blind));
assert.throws(() => parseAnswerJudgment({ ratings: [{ ...rating, label: "B" }] }, blind));
assert.throws(() => parseAnswerJudgment({ ratings: [{ ...rating, evidenceConcern: "fabricated" }] }, blind));
assert.throws(() => parseAnswerJudgment({ ratings: [{ ...rating, severeFabrication: true }] }, blind));
assert.throws(() => parseAnswerJudgment({ ratings: [{ ...rating, evidenceConcern: "contradiction", severeFabrication: true, usable: true }] }, blind));
assert.equal(parseAnswerJudgment({ ratings: [{ ...rating, evidenceConcern: "unconfirmed-personal" }] }, blind)[0].usable, true, "unconfirmed personal context is not automatically a failed answer");
const judge = ANSWER_BENCHMARK_JUDGES[1];
const judgment = await evaluateAnswerJudge(fixture, [result], judge, async (request, stats) => { assert.equal(request.retryUnreadableOutput, false); assert.equal(request.reasoningEffort, "high"); stats.attempts = 1; return { ratings: [rating] }; });
const summary = summarizeAnswers([result, failed], [judgment]);
assert.equal(summary[0].attempted, 2);
assert.equal(summary[0].completed, 1);
assert.equal(summary[0].providerReportedCostUsd, null);
assert.equal(summary[1].score, null);
assert.equal(summary[1].totalTokens, null);
assert.equal(summarizeAnswers([{ ...result, elapsedMs: 1000 }, { ...result, elapsedMs: 5000 }], [judgment])[0].medianSeconds, 3, "even sample median uses both middle observations");
assert.equal(summarizeAnswers([{ ...result, elapsedMs: 4000 }, { ...failed, elapsedMs: 0 }], [judgment])[0].medianSeconds, 4, "failed or skipped requests cannot make completed latency look faster");
assert.equal(summary[0].judgeScores[judge.id], 88);
assert.equal(summary[0].judgeScores["astra-high"], null, "missing judge results remain unknown");
assert.equal(summary[0].dimensions.evidence, 5);
assert.equal(summary[0].evidenceConcerns.none, 1);
const retried = carryFailedAttempt({error:"provider-or-response",attempts:1,elapsedMs:50,usage:null}, {...result,attempts:2,elapsedMs:100});
assert.equal(retried.attempts,3);
assert.equal(retried.elapsedMs,150);
assert.equal(retried.usage,null,"unknown consumed usage remains unknown after retry");
assert.deepEqual(retried.priorErrors,["provider-or-response"]);
assert.equal(carryFailedAttempt({error:"provider-stopped",attempts:0},result).usage,result.usage,"a skipped request does not hide reported consumed usage");
const interrupted = carryFailedAttempt({error:"interrupted-in-flight",attempts:null,elapsedMs:null,usage:null},result);
assert.equal(interrupted.attempts,null,"a killed dispatch group may have consumed an unknown number of requests");
assert.equal(interrupted.usage,null);
assert.equal(interrupted.elapsedMs,null);
const interruptedSummary = summarizeAnswers([interrupted],[])[0];
assert.equal(interruptedSummary.providerRequests,null);
assert.equal(interruptedSummary.medianSeconds,null);
assert.equal(interruptedSummary.latencySamples,0,"unknown interrupted timing cannot be displayed as faster");
const pairedJudgments = ANSWER_BENCHMARK_JUDGES.map(({id}) => ({fixture:"paired",judge:id,ratings:[{arm:"sol-high",score:95},{arm:"sol-medium",score:id==="astra-high"?96:90}]}));
const paired = compareAnswerSettings(pairedJudgments).find(({arm})=>arm==="sol-medium");
assert.deepEqual(paired,{arm:"sol-medium",reference:"sol-high",pairedCases:1,meanDifference:-2,wins:0,ties:0,losses:1});
assert.equal(compareAnswerSettings(pairedJudgments.slice(0,1)).find(({arm})=>arm==="sol-medium").pairedCases,0,"paired comparisons require both judges for both answers");
